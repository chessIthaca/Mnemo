//! OpenSpec schema and project-config loading for the plan board.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Component, Path, PathBuf};

use serde::{Deserialize, Deserializer, Serialize};
use serde_norway::Value;

/// A schema together with the project config that supplied its fallback and rules.
#[derive(Debug, Clone)]
pub struct ResolvedSchema {
    /// The resolved schema.
    pub schema: Schema,
    /// `.coding/openspec/config.yaml`, or defaults when it is absent.
    pub config: OpenSpecConfig,
}

impl ResolvedSchema {
    /// Non-fatal unknown-field warnings from both loaded files.
    pub fn warnings(&self) -> Vec<String> {
        self.schema
            .warnings
            .iter()
            .chain(&self.config.warnings)
            .cloned()
            .collect()
    }
}

/// Project-level OpenSpec configuration.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct OpenSpecConfig {
    /// Default schema name when a plan has no recorded schema.
    #[serde(default)]
    pub schema: Option<String>,
    /// Project context included in every worker's plan brief.
    #[serde(default)]
    pub context: String,
    /// Additional rules keyed by artifact id.
    #[serde(default, deserialize_with = "deserialize_rules")]
    pub rules: BTreeMap<String, Vec<String>>,
    /// Unrecognised config keys, retained for forwards compatibility.
    #[serde(flatten)]
    pub extra: BTreeMap<String, Value>,
    /// Non-fatal problems found while loading.
    #[serde(skip)]
    pub warnings: Vec<String>,
}

impl OpenSpecConfig {
    /// Load `config.yaml` beneath an OpenSpec directory. A missing file is the
    /// empty configuration; malformed YAML is an error.
    pub fn load(openspec_dir: &Path) -> Result<Self, String> {
        let path = openspec_dir.join("config.yaml");
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok(Self::default());
            }
            Err(error) => {
                return Err(format!("could not read '{}': {error}", path.display()));
            }
        };
        let mut config: Self = serde_norway::from_str(&text)
            .map_err(|error| format!("could not parse '{}': {error}", path.display()))?;
        config.warnings = config
            .extra
            .keys()
            .map(|key| format!("{}: unknown field '{key}'", path.display()))
            .collect();
        Ok(config)
    }
}

/// An OpenSpec workflow schema.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Schema {
    /// Schema name used by config and plan metadata.
    pub name: String,
    /// Schema version, accepted as either a YAML string or number.
    #[serde(deserialize_with = "deserialize_version")]
    pub version: String,
    /// Human-readable workflow description.
    #[serde(default)]
    pub description: String,
    /// Artifacts in their authoring order.
    pub artifacts: Vec<Artifact>,
    /// Requirements for starting implementation.
    #[serde(default)]
    pub apply: Apply,
    /// Unrecognised schema keys, retained for forwards compatibility.
    #[serde(flatten)]
    pub extra: BTreeMap<String, Value>,
    /// Non-fatal unknown-field warnings.
    #[serde(skip)]
    pub warnings: Vec<String>,
}

/// One artifact generated by a schema.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Artifact {
    /// Stable id used by `requires`, config rules, and plan sections.
    pub id: String,
    /// Output filename or glob the artifact generates.
    pub generates: String,
    /// Optional artifact description used by upstream OpenSpec schemas.
    #[serde(default)]
    pub description: Option<String>,
    /// Template filename beneath the schema's `templates/` directory.
    pub template: String,
    /// Authoring instruction included in worker plan briefs.
    #[serde(default)]
    pub instruction: String,
    /// Artifacts that must exist before this one.
    #[serde(default)]
    pub requires: Vec<String>,
    /// The loaded template body.
    #[serde(skip)]
    pub template_text: String,
    /// Unrecognised artifact keys, retained for forwards compatibility.
    #[serde(flatten)]
    pub extra: BTreeMap<String, Value>,
}

/// The schema's implementation gate.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Apply {
    /// Artifacts required before `team_dispatch`.
    #[serde(default)]
    pub requires: Vec<String>,
    /// Task file tracked by OpenSpec's apply operation.
    #[serde(default)]
    pub tracks: String,
    /// Unrecognised apply keys, retained for forwards compatibility.
    #[serde(flatten)]
    pub extra: BTreeMap<String, Value>,
}

impl Schema {
    /// Load and validate one schema folder containing `schema.yaml` and
    /// `templates/`. Every referenced template is read into its artifact.
    pub fn load(schema_dir: &Path) -> Result<Self, String> {
        let path = schema_dir.join("schema.yaml");
        let text = std::fs::read_to_string(&path)
            .map_err(|error| format!("could not read '{}': {error}", path.display()))?;
        let mut schema: Self = serde_norway::from_str(&text)
            .map_err(|error| format!("could not parse '{}': {error}", path.display()))?;
        if schema.name.trim().is_empty() {
            return Err(format!("{}: schema name is empty", path.display()));
        }
        if schema.version.trim().is_empty() {
            return Err(format!("{}: schema version is empty", path.display()));
        }
        let mut warnings = unknown_warnings(&path, "schema", &schema.extra);
        warnings.extend(unknown_warnings(&path, "apply", &schema.apply.extra));

        let mut ids = BTreeSet::new();
        for artifact in &mut schema.artifacts {
            if artifact.id.trim().is_empty()
                || artifact.id.contains(['\r', '\n'])
                || artifact.generates.trim().is_empty()
            {
                return Err(format!(
                    "{}: every artifact needs a single-line id and a generates value",
                    path.display()
                ));
            }
            if !ids.insert(artifact.id.clone()) {
                return Err(format!(
                    "{}: duplicate artifact id '{}'",
                    path.display(),
                    artifact.id
                ));
            }
            warnings.extend(unknown_warnings(
                &path,
                &format!("artifact '{}'", artifact.id),
                &artifact.extra,
            ));
            let template = safe_relative(&artifact.template).ok_or_else(|| {
                format!(
                    "{}: artifact '{}' template must be a relative path inside templates/",
                    path.display(),
                    artifact.id
                )
            })?;
            let template_path = schema_dir.join("templates").join(template);
            artifact.template_text = std::fs::read_to_string(&template_path).map_err(|error| {
                format!(
                    "{}: artifact '{}' template '{}': {error}",
                    path.display(),
                    artifact.id,
                    template_path.display()
                )
            })?;
        }
        for artifact in &schema.artifacts {
            for required in &artifact.requires {
                if !ids.contains(required) {
                    return Err(format!(
                        "{}: artifact '{}' requires unknown artifact '{required}'",
                        path.display(),
                        artifact.id
                    ));
                }
            }
        }
        for required in &schema.apply.requires {
            if !ids.contains(required) {
                return Err(format!(
                    "{}: apply requires unknown artifact '{required}'",
                    path.display()
                ));
            }
        }
        validate_acyclic(&schema, &path)?;
        schema.warnings = warnings;
        Ok(schema)
    }

    /// Resolve a recorded `name@version`, then the project config's schema,
    /// then the built-in `spec-driven`. Custom schemas are looked up in the
    /// project before the user-level OpenSpec schema directory.
    pub fn resolve(
        openspec_dir: &Path,
        recorded: Option<&str>,
    ) -> Result<ResolvedSchema, String> {
        let config = OpenSpecConfig::load(openspec_dir)?;
        let recorded_name = recorded.map(schema_name).transpose()?;
        let name = recorded_name
            .as_deref()
            .or(config.schema.as_deref().map(str::trim).filter(|s| !s.is_empty()))
            .unwrap_or("spec-driven");
        let schema = if name == "spec-driven" {
            Self::spec_driven()
        } else {
            let safe_name = safe_component(name).ok_or_else(|| {
                format!("invalid OpenSpec schema name '{name}': expected one path component")
            })?;
            let project = openspec_dir.join("schemas").join(safe_name);
            if project.join("schema.yaml").is_file() {
                Self::load(&project)?
            } else if let Some(user) = user_schema_dir(safe_name) {
                if user.join("schema.yaml").is_file() {
                    Self::load(&user)?
                } else {
                    return Err(schema_not_found(name, &project, &user));
                }
            } else {
                return Err(format!(
                    "OpenSpec schema '{name}' was not found at '{}'",
                    project.display()
                ));
            }
        };
        Ok(ResolvedSchema { schema, config })
    }

    /// The built-in schema, available without any files on disk.
    pub fn spec_driven() -> Self {
        let artifacts = vec![
            builtin_artifact(
                "proposal",
                "proposal.md",
                "Explain why the change is needed and what changes, without designing the implementation.",
                "# Why\n\n# What Changes\n",
                &[],
            ),
            builtin_artifact(
                "specs",
                "specs/**/*.md",
                "Describe observable requirements with SHALL or MUST text and WHEN/THEN scenarios.",
                "## ADDED Requirements\n\n### Requirement: Name\nThe system SHALL ...\n\n#### Scenario: Name\n- **WHEN** ...\n- **THEN** ...\n",
                &["proposal"],
            ),
            builtin_artifact(
                "design",
                "design.md",
                "Record technical decisions, alternatives, migration concerns, and interfaces.",
                "## Context\n\n## Decisions\n",
                &["proposal"],
            ),
            builtin_artifact(
                "tasks",
                "tasks.md",
                "Turn the proposal, specs, and design into ordered, verifiable implementation steps.",
                "## Tasks\n\n- [ ] Implement the change\n",
                &["specs", "design"],
            ),
        ];
        Self {
            name: "spec-driven".to_string(),
            version: "1".to_string(),
            description: "Default OpenSpec workflow — proposal, specs, design, tasks".to_string(),
            artifacts,
            apply: Apply {
                requires: vec!["tasks".to_string()],
                tracks: "tasks.md".to_string(),
                extra: BTreeMap::new(),
            },
            extra: BTreeMap::new(),
            warnings: vec![],
        }
    }

    /// The durable schema reference recorded on a plan.
    pub fn reference(&self) -> String {
        format!("{}@{}", self.name, self.version)
    }

    /// Find an artifact by id.
    pub fn artifact(&self, id: &str) -> Option<&Artifact> {
        self.artifacts.iter().find(|artifact| artifact.id == id)
    }
}

fn builtin_artifact(
    id: &str,
    generates: &str,
    instruction: &str,
    template_text: &str,
    requires: &[&str],
) -> Artifact {
    Artifact {
        id: id.to_string(),
        generates: generates.to_string(),
        description: None,
        template: format!("{id}.md"),
        instruction: instruction.to_string(),
        requires: requires.iter().map(|id| (*id).to_string()).collect(),
        template_text: template_text.to_string(),
        extra: BTreeMap::new(),
    }
}

fn unknown_warnings(
    path: &Path,
    scope: &str,
    extra: &BTreeMap<String, Value>,
) -> Vec<String> {
    extra
        .keys()
        .map(|key| format!("{}: {scope}: unknown field '{key}'", path.display()))
        .collect()
}

fn schema_name(recorded: &str) -> Result<String, String> {
    let trimmed = recorded.trim();
    let (name, version) = trimmed
        .rsplit_once('@')
        .map(|(name, version)| (name, Some(version)))
        .unwrap_or((trimmed, None));
    if name.trim().is_empty() || version.is_some_and(|version| version.trim().is_empty()) {
        return Err(format!(
            "invalid recorded OpenSpec schema '{recorded}': expected name@version"
        ));
    }
    Ok(name.trim().to_string())
}

fn safe_component(name: &str) -> Option<&str> {
    let mut components = Path::new(name).components();
    match (components.next(), components.next()) {
        (Some(Component::Normal(component)), None) if component == name => Some(name),
        _ => None,
    }
}

fn safe_relative(path: &str) -> Option<&Path> {
    let path = Path::new(path);
    if path.as_os_str().is_empty()
        || path.is_absolute()
        || path
            .components()
            .any(|component| !matches!(component, Component::Normal(_)))
    {
        None
    } else {
        Some(path)
    }
}

fn user_schema_dir(name: &str) -> Option<PathBuf> {
    std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .map(PathBuf::from)
        .map(|home| {
            home.join(".local")
                .join("share")
                .join("openspec")
                .join("schemas")
                .join(name)
        })
}

fn schema_not_found(name: &str, project: &Path, user: &Path) -> String {
    format!(
        "OpenSpec schema '{name}' was not found at '{}' or '{}'",
        project.display(),
        user.display()
    )
}

fn validate_acyclic(schema: &Schema, path: &Path) -> Result<(), String> {
    fn visit(
        id: &str,
        schema: &Schema,
        path: &Path,
        visiting: &mut BTreeSet<String>,
        finished: &mut BTreeSet<String>,
        stack: &mut Vec<String>,
    ) -> Result<(), String> {
        if finished.contains(id) {
            return Ok(());
        }
        if !visiting.insert(id.to_string()) {
            let start = stack.iter().position(|item| item == id).unwrap_or(0);
            let mut cycle = stack[start..].to_vec();
            cycle.push(id.to_string());
            return Err(format!(
                "{}: artifact requires cycle: {}",
                path.display(),
                cycle.join(" -> ")
            ));
        }
        stack.push(id.to_string());
        if let Some(artifact) = schema.artifact(id) {
            for required in &artifact.requires {
                visit(required, schema, path, visiting, finished, stack)?;
            }
        }
        stack.pop();
        visiting.remove(id);
        finished.insert(id.to_string());
        Ok(())
    }

    let mut visiting = BTreeSet::new();
    let mut finished = BTreeSet::new();
    let mut stack = Vec::new();
    for artifact in &schema.artifacts {
        visit(
            &artifact.id,
            schema,
            path,
            &mut visiting,
            &mut finished,
            &mut stack,
        )?;
    }
    Ok(())
}

fn deserialize_version<'de, D>(deserializer: D) -> Result<String, D::Error>
where
    D: Deserializer<'de>,
{
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum Version {
        Text(String),
        Number(serde_norway::Number),
    }
    Ok(match Version::deserialize(deserializer)? {
        Version::Text(version) => version,
        Version::Number(version) => version.to_string(),
    })
}

#[derive(Deserialize)]
#[serde(untagged)]
enum Rule {
    One(String),
    Many(Vec<String>),
}

fn deserialize_rules<'de, D>(deserializer: D) -> Result<BTreeMap<String, Vec<String>>, D::Error>
where
    D: Deserializer<'de>,
{
    let rules = BTreeMap::<String, Rule>::deserialize(deserializer)?;
    Ok(rules
        .into_iter()
        .map(|(id, rule)| {
            let rules = match rule {
                Rule::One(rule) => vec![rule],
                Rule::Many(rules) => rules,
            };
            (id, rules)
        })
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write_schema(root: &Path, name: &str, yaml: &str, templates: &[(&str, &str)]) -> PathBuf {
        let dir = root.join("schemas").join(name);
        std::fs::create_dir_all(dir.join("templates")).unwrap();
        std::fs::write(dir.join("schema.yaml"), yaml).unwrap();
        for (path, text) in templates {
            std::fs::write(dir.join("templates").join(path), text).unwrap();
        }
        dir
    }

    #[test]
    fn loads_numeric_versions_rules_and_unknown_field_warnings() {
        let dir = tempfile::tempdir().unwrap();
        let schema_dir = write_schema(
            dir.path(),
            "research",
            "name: research\nversion: 2\ndescription: Research first\nfuture: retained\nartifacts:\n  - id: research\n    generates: research.md\n    template: research.md\n    instruction: Investigate first\n    future_artifact: retained\napply:\n  requires: [research]\n  tracks: research.md\n  future_apply: retained\n",
            &[("research.md", "# Findings\n")],
        );
        let schema = Schema::load(&schema_dir).unwrap();
        assert_eq!(schema.reference(), "research@2");
        assert_eq!(schema.artifacts[0].template_text, "# Findings\n");
        assert_eq!(schema.extra["future"], "retained");
        assert_eq!(schema.artifacts[0].extra["future_artifact"], "retained");
        assert_eq!(schema.warnings.len(), 3, "{:?}", schema.warnings);

        std::fs::write(
            dir.path().join("config.yaml"),
            "schema: research\ncontext: Use the existing store.\nrules:\n  research: Cite sources\n  tasks:\n    - Name tests\n    - Name files\nfuture_config: retained\n",
        )
        .unwrap();
        let resolved = Schema::resolve(dir.path(), None).unwrap();
        assert_eq!(resolved.schema.name, "research");
        assert_eq!(resolved.config.rules["research"], vec!["Cite sources"]);
        assert_eq!(resolved.config.rules["tasks"].len(), 2);
        assert_eq!(resolved.config.extra["future_config"], "retained");
        assert_eq!(resolved.warnings().len(), 4);
    }

    #[test]
    fn rejects_missing_templates_duplicate_ids_and_cycles() {
        let dir = tempfile::tempdir().unwrap();
        let missing = write_schema(
            dir.path(),
            "missing",
            "name: missing\nversion: 1\nartifacts:\n  - id: research\n    generates: research.md\n    template: absent.md\n",
            &[],
        );
        let error = Schema::load(&missing).unwrap_err();
        assert!(error.contains("absent.md"), "{error}");

        let duplicate = write_schema(
            dir.path(),
            "duplicate",
            "name: duplicate\nversion: 1\nartifacts:\n  - {id: same, generates: one.md, template: same.md}\n  - {id: same, generates: two.md, template: same.md}\n",
            &[("same.md", "template")],
        );
        assert!(Schema::load(&duplicate)
            .unwrap_err()
            .contains("duplicate artifact id 'same'"));

        let cycle = write_schema(
            dir.path(),
            "cycle",
            "name: cycle\nversion: 1\nartifacts:\n  - {id: research, generates: research.md, template: same.md, requires: [proposal]}\n  - {id: proposal, generates: proposal.md, template: same.md, requires: [research]}\n",
            &[("same.md", "template")],
        );
        let error = Schema::load(&cycle).unwrap_err();
        assert!(error.contains("requires cycle"), "{error}");
        assert!(error.contains("research -> proposal -> research"), "{error}");
    }

    #[test]
    fn resolution_prefers_recorded_schema_then_config_then_builtin() {
        let dir = tempfile::tempdir().unwrap();
        write_schema(
            dir.path(),
            "custom",
            "name: custom\nversion: 3\nartifacts:\n  - {id: tasks, generates: tasks.md, template: tasks.md}\napply: {requires: [tasks], tracks: tasks.md}\n",
            &[("tasks.md", "tasks")],
        );
        std::fs::write(dir.path().join("config.yaml"), "schema: custom\n").unwrap();
        assert_eq!(Schema::resolve(dir.path(), None).unwrap().schema.reference(), "custom@3");
        assert_eq!(
            Schema::resolve(dir.path(), Some("spec-driven@1"))
                .unwrap()
                .schema
                .reference(),
            "spec-driven@1"
        );
        std::fs::remove_file(dir.path().join("config.yaml")).unwrap();
        assert_eq!(
            Schema::resolve(dir.path(), None).unwrap().schema.reference(),
            "spec-driven@1"
        );
    }

    #[test]
    fn missing_config_is_the_empty_config() {
        let dir = tempfile::tempdir().unwrap();
        let config = OpenSpecConfig::load(dir.path()).unwrap();
        assert!(config.schema.is_none());
        assert!(config.context.is_empty());
        assert!(config.rules.is_empty());
    }
}
