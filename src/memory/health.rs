/// The generated report's path, relative to the workspace root.
pub const REPORT_REL_PATH: &str = ".coding/knowledge/HEALTH.md";

/// The rename-resolution cache, relative to the workspace root (gitignored
/// together with the report).
pub const STATE_REL_PATH: &str = ".coding/knowledge/.health-state.json";

/// The `data` key the pass stamps onto an affected knowledge row.
pub const MOVED_PATHS_KEY: &str = "moved_paths";

/// How many moved-path entries `memory_search` renders before `+N more`.
pub const ANNOTATION_MAX_ENTRIES: usize = 4;

/// The report's first line — the decision's wording, so nobody edits it.
pub const REPORT_HEADER: &str =
    "Generated by the memory check pass. Do not edit: fix or supersede the cited record.";

/// The citation rule: a repo-relative path with a file extension, under one of
/// the project's source trees. URLs and `[[wiki-link]]` targets are blanked
/// before the match, and `.coding/…` paths carry no listed prefix, so none of
/// them count as citations.
pub(crate) const CITATION_PATTERN: &str = r"\b((?:src|src-tauri|mnemo2|frontend|tests|scripts|docs)/[\w./-]+\.\w+)";

/// Scheme-qualified tokens (URLs) — blanked before citation matching so a path
/// embedded in a link never reads as a citation of this repo.
pub(crate) const URL_PATTERN: &str = r"\S*://\S*";

/// How many rename hops a moved path may take before it counts as gone.
const MAX_RENAME_HOPS: usize = 5;

/// The cache's on-disk shape version.
const STATE_VERSION: u32 = 1;

/// The article's guidance for an injected instruction file (lines / bytes).
const CONSTITUTION_MAX_LINES: usize = 200;
/// See [`CONSTITUTION_MAX_LINES`].
const CONSTITUTION_MAX_BYTES: usize = 25 * 1024;

/// The knowledge corpus' type dirs — the same four the indexer scans.
const KNOWLEDGE_TYPES: [MemoryRecordType; 4] = [
    MemoryRecordType::Spec,
    MemoryRecordType::Decision,
    MemoryRecordType::Bug,
    MemoryRecordType::How,
];

/// One stale citation: the path a record names and where it went.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MovedPath {
    /// The cited path, repo-relative with forward slashes.
    pub from: String,
    /// Where git says it went; `None` when the path was deleted outright.
    pub to: Option<String>,
}

/// One knowledge file citing at least one path the repo no longer has.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StaleRecord {
    /// The record's path relative to the knowledge root
    /// (`decision/2026-08-23-….md`).
    pub rel_path: String,
    /// The missing citations, sorted by `from`.
    pub moved: Vec<MovedPath>,
}

/// One `[[target]]` that resolves to nothing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnresolvedLink {
    /// The record holding the link, relative to the knowledge root.
    pub rel_path: String,
    /// The link target, verbatim.
    pub target: String,
}

/// Live typed records sharing a record type and a normalized title.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DuplicateTitle {
    /// The shared record type (typed rows only — `None` never groups).
    pub record_type: MemoryRecordType,
    /// The bare title (no typed prefix), as one member spells it.
    pub title: String,
    /// Where each member lives, sorted: the record's `rel_path` for a
    /// knowledge row, `id <uuid>` for anything else.
    pub records: Vec<String>,
}

/// A line/byte count for one measured text.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Size {
    /// `str::lines().count()` of the measured text.
    pub lines: usize,
    /// UTF-8 byte length of the measured text.
    pub bytes: usize,
}

impl Size {
    /// Whether the text exceeds either guidance limit.
    pub fn over_budget(&self) -> bool {
        self.lines > CONSTITUTION_MAX_LINES || self.bytes > CONSTITUTION_MAX_BYTES
    }
}

/// `agent.md`'s size, raw and per workflow scope.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct ConstitutionSize {
    /// Whether the project has an `agent.md` at all.
    pub present: bool,
    /// The file as written (every scope's text included).
    pub raw: Size,
    /// What a Classic-workflow session loads.
    pub classic: Size,
    /// What a Mnemo2 lead/worker session loads.
    pub team: Size,
}

/// What one pass found and did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HealthReport {
    /// Records citing paths the repo no longer has, sorted by rel path.
    pub stale_paths: Vec<StaleRecord>,
    /// `[[links]]` that resolve to nothing, sorted by (record, target).
    pub unresolved_links: Vec<UnresolvedLink>,
    /// Duplicate-title groups, sorted by (record type, title).
    pub duplicate_titles: Vec<DuplicateTitle>,
    /// `agent.md`'s size per scope.
    pub constitution: ConstitutionSize,
    /// The generated report's absolute path.
    pub report_path: PathBuf,
    /// Whether this pass rewrote the report (its bytes changed).
    pub report_written: bool,
    /// Whether this pass rewrote the rename cache.
    pub cache_written: bool,
    /// How many derived rows this pass re-stamped with `moved_paths`.
    pub rows_updated: usize,
}

impl HealthReport {
    /// The counts, as one status-line fragment: `"117 records cite missing
    /// paths · 2 unresolved links · 3 duplicate titles"`.
    pub fn summary(&self) -> String {
        format!(
            "{} records cite missing paths · {} unresolved links · {} duplicate titles",
            self.stale_paths.len(),
            self.unresolved_links.len(),
            self.duplicate_titles.len()
        )
    }
}

/// How the pass reaches git history. The production probe spawns `git`
/// through the engine's hardened helper; tests inject a counter or a stub, so
/// a pass's spawn count is observable.
trait GitProbe: Send + Sync {
    /// Run one git command in `root` and return its raw stdout.
    fn run(&self, root: &Path, args: &[&str]) -> std::result::Result<String, String>;
}

/// The production probe: the engine's hardened `git` spawn (no console
/// window, environment scrubbed).
struct RealGit;

impl GitProbe for RealGit {
    fn run(&self, root: &Path, args: &[&str]) -> std::result::Result<String, String> {
        crate::project::git_ops::git_raw(root, args)
    }
}

/// Run the memory check pass for one project: read the knowledge corpus and
/// the live semantic rows, check them, write the report and the rename cache,
/// and stamp `moved_paths` onto the affected derived rows.
///
/// Never blocks the caller's thread on the scan (it runs on the blocking
/// pool), never edits an authored record, and never deletes anything. The
/// call fails only on a store error, so a caller can treat a failure as a
/// warning rather than a project-open failure.
pub async fn run(store: &dyn MemoryStoreTrait, workspace_root: &Path) -> Result<HealthReport> {
    run_with_git(store, workspace_root, Arc::new(RealGit)).await
}

/// [`run`] with an injectable git probe (tests count the spawns).
async fn run_with_git(
    store: &dyn MemoryStoreTrait,
    workspace_root: &Path,
    git: Arc<dyn GitProbe>,
) -> Result<HealthReport> {
    // Live semantic rows carry the titles (links, duplicates) and the
    // `moved_paths` a previous pass stamped.
    let rows = store
        .list_filtered(&MemoryFilter::new().tier(MemoryTier::Semantic))
        .await?;
    let root = workspace_root.to_path_buf();
    let scanned = tokio::task::spawn_blocking(move || scan(&root, &rows, git.as_ref()))
        .await
        .map_err(|e| Error::Memory(format!("memory health scan task failed: {e}")))?;

    // Re-stamp only rows whose value changed — a settled pass writes nothing.
    let mut rows_updated = 0;
    for (id, moved) in &scanned.row_updates {
        let Some(row) = store.get_memory(id).await? else {
            continue;
        };
        let Some(data) = merge_moved_paths(&row.data, moved) else {
            continue;
        };
        if store
            .set_derived_metadata(id, row.superseded_by.as_deref(), &data)
            .await?
        {
            rows_updated += 1;
        }
    }
    // An open rebuilds a missing index file (plan 373dec00 step 6): the
    // generation is cheap, deterministic and a no-op when the bytes match.
    crate::memory::knowledge_index::regenerate_blocking(
        workspace_root.join(".coding").join(knowledge::KNOWLEDGE_DIR_NAME),
    )
    .await;
    Ok(HealthReport {
        rows_updated,
        ..scanned.report
    })
}

/// The pass's blocking half: everything that touches the filesystem or git.
struct Scan {
    report: HealthReport,
    /// Derived rows to (re)stamp: memory id plus the moved paths the row
    /// should carry. An empty list means "drop the key" (the record no longer
    /// cites a missing path).
    row_updates: Vec<(String, Vec<MovedPath>)>,
}

/// Run the four checks over `root` and write what changed. Pure with respect to
/// the store — the async half applies [`Scan::row_updates`].
fn scan(root: &Path, rows: &[Memory], git: &dyn GitProbe) -> Scan {
    let knowledge_dir = root.join(".coding").join(knowledge::KNOWLEDGE_DIR_NAME);
    let records = read_corpus(&knowledge_dir);
    let citation_re = Regex::new(CITATION_PATTERN).expect("the citation pattern is a fixed regex");
    let url_re = Regex::new(URL_PATTERN).expect("the URL pattern is a fixed regex");

    // Superseded files are history: never reported, never stamped — but they
    // still resolve a `[[link]]` (see `link_names`).
    let live: Vec<usize> = records
        .iter()
        .enumerate()
        .filter(|(_, (_, record))| record.status != KnowledgeStatus::Superseded)
        .map(|(index, _)| index)
        .collect();

    // Every live record's citations, sorted and deduped (an empty body costs
    // one regex scan and yields nothing).
    let cited: Vec<(String, Vec<String>)> = live
        .iter()
        .map(|&index| {
            let (rel, record) = &records[index];
            (
                rel.clone(),
                extract_citations(&citation_re, &url_re, &record.body),
            )
        })
        .collect();

    // The distinct missing paths, resolved once per pass.
    let mut missing: BTreeSet<String> = BTreeSet::new();
    for (_, paths) in &cited {
        for path in paths {
            if !root.join(path).exists() {
                missing.insert(path.clone());
            }
        }
    }
    let (resolved, cache_written) =
        resolve_missing_paths(root, &missing, &root.join(STATE_REL_PATH), git);

    // The per-record findings, plus the row stamp for each affected record.
    let mut stale_paths: Vec<StaleRecord> = Vec::new();
    let mut row_updates: Vec<(String, Vec<MovedPath>)> = Vec::new();
    for (rel, paths) in &cited {
        let moved: Vec<MovedPath> = paths
            .iter()
            .filter(|path| missing.contains(*path))
            .map(|path| MovedPath {
                from: path.clone(),
                to: resolved.get(path).cloned().flatten(),
            })
            .collect();
        if moved.is_empty() {
            continue;
        }
        row_updates.push((knowledge_id(rel), moved.clone()));
        stale_paths.push(StaleRecord {
            rel_path: rel.clone(),
            moved,
        });
    }
    // A record that no longer cites a missing path loses its stale stamp. A
    // superseded record is history: it is left exactly as it is.
    let affected: BTreeSet<&str> = stale_paths.iter().map(|s| s.rel_path.as_str()).collect();
    let superseded: BTreeSet<&str> = records
        .iter()
        .filter(|(_, record)| record.status == KnowledgeStatus::Superseded)
        .map(|(rel, _)| rel.as_str())
        .collect();
    for row in rows {
        let Some(rel) = row.data.get("rel_path").and_then(|value| value.as_str()) else {
            continue;
        };
        if affected.contains(rel) || superseded.contains(rel) {
            continue;
        }
        if row.data.get(MOVED_PATHS_KEY).is_some() {
            row_updates.push((row.id.clone(), Vec::new()));
        }
    }

    // Wiki-links that resolve to nothing. Only real link shapes count here:
    // TOML array headers (`[[bin]]`, `[[patch.unused]]`) and word mentions
    // (`[[links]]`) look like links to `extract_links` but never name a record.
    let names = link_names(&records, rows);
    let mut unresolved: BTreeSet<(String, String)> = BTreeSet::new();
    for &index in &live {
        let (rel, record) = &records[index];
        for link in &record.links {
            if !looks_like_link_target(&link.target) {
                continue;
            }
            if !link_resolves(root, &knowledge_dir, &names, link) {
                unresolved.insert((rel.clone(), link.target.clone()));
            }
        }
    }
    let unresolved_links: Vec<UnresolvedLink> = unresolved
        .into_iter()
        .map(|(rel_path, target)| UnresolvedLink { rel_path, target })
        .collect();

    let duplicate_titles = duplicate_titles(rows);
    let constitution = measure_constitution(root);

    // Write the report only when its bytes change (a settled pass writes
    // nothing). The guard skips a project with no knowledge corpus at all:
    // this pass reports on knowledge records, it never creates the corpus.
    let report_path = root.join(REPORT_REL_PATH);
    let report_written = if knowledge_dir.is_dir() {
        write_if_changed(
            &report_path,
            &render_report(
                &stale_paths,
                &unresolved_links,
                &duplicate_titles,
                &constitution,
            ),
        )
    } else {
        false
    };

    Scan {
        report: HealthReport {
            stale_paths,
            unresolved_links,
            duplicate_titles,
            constitution,
            report_path,
            report_written,
            cache_written,
            rows_updated: 0,
        },
        row_updates,
    }
}

/// Every `.md` record in the corpus' four type dirs, as `(rel_path, record)`,
/// sorted by rel path so every downstream list is deterministic.
///
/// Shared with [`crate::memory::knowledge_index`], which renders the same
/// corpus as `.coding/knowledge/INDEX.md`.
pub(crate) fn read_corpus(knowledge_dir: &Path) -> Vec<(String, KnowledgeRecord)> {
    let mut records = Vec::new();
    for record_type in KNOWLEDGE_TYPES {
        let Some(dir_name) = knowledge::dir_for_record_type(record_type) else {
            continue;
        };
        let Ok(entries) = std::fs::read_dir(knowledge_dir.join(dir_name)) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("md") {
                continue;
            }
            let Ok(text) = std::fs::read_to_string(&path) else {
                continue;
            };
            // Forward-slash rel path regardless of platform separators —
            // `parse_file` splits on '/'.
            let rel = format!("{dir_name}/{}", entry.file_name().to_string_lossy());
            if let Some(record) = knowledge::parse_file(&rel, &text) {
                records.push((rel, record));
            }
        }
    }
    records.sort_by(|a, b| a.0.cmp(&b.0));
    records
}

/// The repo paths one record body cites, sorted and deduped.
///
/// Shared with [`crate::memory::knowledge_index`]: the generated INDEX.md's
/// area rule is the same citation rule this pass checks against the repo.
pub(crate) fn extract_citations(citation_re: &Regex, url_re: &Regex, body: &str) -> Vec<String> {
    let without_urls = url_re.replace_all(body, " ");
    let text = strip_links(&without_urls);
    let mut paths: BTreeSet<String> = BTreeSet::new();
    for capture in citation_re.captures_iter(&text) {
        if let Some(path) = capture.get(1) {
            paths.insert(path.as_str().to_string());
        }
    }
    paths.into_iter().collect()
}

/// Replace every `[[target]]` span with spaces, so a wiki-link target is never
/// also read as a citation (links have their own check).
fn strip_links(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("[[") {
        out.push_str(&rest[..start]);
        let tail = &rest[start..];
        match tail.find("]]") {
            Some(end) => {
                out.push_str(&" ".repeat(end + 2));
                rest = &tail[end + 2..];
            }
            None => {
                out.push_str(tail);
                rest = "";
            }
        }
    }
    out.push_str(rest);
    out
}

/// Resolve every missing path, through the cache when it still holds, through
/// git otherwise. Returns the resolution map and whether the cache changed.
fn resolve_missing_paths(
    root: &Path,
    missing: &BTreeSet<String>,
    state_path: &Path,
    git: &dyn GitProbe,
) -> (BTreeMap<String, Option<String>>, bool) {
    let mut state = load_state(state_path);
    let mut changed = false;
    let mut resolved = BTreeMap::new();
    // One git failure ends the lookups for this pass: a non-git project must
    // not spawn once per path on every open, and a transient failure must not
    // be cached as "gone".
    let mut git_failed = false;
    for path in missing {
        match state.resolved.get(path) {
            // A cached new home holds while it still exists on disk.
            Some(Some(to)) if root.join(to).exists() => {
                resolved.insert(path.clone(), Some(to.clone()));
                continue;
            }
            // A cached "gone" is final: git history only grows.
            Some(None) => {
                resolved.insert(path.clone(), None);
                continue;
            }
            // Uncached, or the cached home has vanished: resolve again.
            _ => {}
        }
        if git_failed {
            // Unknown for this pass — reported gone, never cached: the next
            // pass tries again.
            resolved.insert(path.clone(), None);
            continue;
        }
        match resolve_missing(root, git, path) {
            Resolved::Answered(to) => {
                if state.resolved.get(path) != Some(&to) {
                    state.resolved.insert(path.clone(), to.clone());
                    changed = true;
                }
                resolved.insert(path.clone(), to);
            }
            Resolved::Failed => {
                git_failed = true;
                resolved.insert(path.clone(), None);
            }
        }
    }
    let written = changed && write_state(state_path, &state);
    (resolved, written)
}

/// One rename lookup's answer. A git failure is [`Resolved::Failed`], never
/// "gone": an unknown path must not be cached as a dead end for every later
/// pass.
enum Resolved {
    /// The path's new home, or `None` when it was deleted outright.
    Answered(Option<String>),
    /// Git could not answer (binary missing, a lock, a timeout, not a repo).
    Failed,
}

/// Follow one missing path to its new home: the commit that deleted it, then
/// that commit's rename entry. A chain (`a → b → c`) is followed up to
/// [`MAX_RENAME_HOPS`]. `Answered(None)` means gone; [`Resolved::Failed`] means
/// git could not answer.
fn resolve_missing(root: &Path, git: &dyn GitProbe, path: &str) -> Resolved {
    let mut current = path.to_string();
    for _ in 0..MAX_RENAME_HOPS {
        if root.join(&current).exists() {
            return Resolved::Answered(Some(current));
        }
        let deleted = match git.run(
            root,
            &["log", "-1", "--diff-filter=D", "--format=%H", "--", &current],
        ) {
            Ok(output) => output,
            Err(_) => return Resolved::Failed,
        };
        let commit = deleted.trim();
        if commit.is_empty() {
            return Resolved::Answered(None);
        }
        let diff = match git.run(
            root,
            &[
                "diff-tree",
                "-r",
                "-M",
                "--name-status",
                "--no-commit-id",
                commit,
            ],
        ) {
            Ok(output) => output,
            Err(_) => return Resolved::Failed,
        };
        match rename_target(&diff, &current) {
            Some(next) => current = next,
            None => return Resolved::Answered(None),
        }
    }
    Resolved::Answered(root.join(&current).exists().then_some(current))
}

/// The `to` side of the rename entry for `from` in a `--name-status` diff.
fn rename_target(diff: &str, from: &str) -> Option<String> {
    for line in diff.lines() {
        let mut fields = line.split('\t');
        let Some(status) = fields.next() else {
            continue;
        };
        if !status.starts_with('R') {
            continue;
        }
        let (Some(old), Some(new)) = (fields.next(), fields.next()) else {
            continue;
        };
        if old == from {
            return Some(new.to_string());
        }
    }
    None
}

/// The cache's on-disk shape.
#[derive(Debug, Default, Serialize, Deserialize)]
struct HealthState {
    /// [`STATE_VERSION`]; a different shape is discarded, never migrated.
    version: u32,
    /// Cited path → its resolution (`null` = gone).
    resolved: BTreeMap<String, Option<String>>,
}

/// Load the rename cache; anything missing, unreadable or from another shape
/// starts empty — the cache is an optimization, never a dependency.
fn load_state(path: &Path) -> HealthState {
    let parsed = std::fs::read_to_string(path)
        .ok()
        .and_then(|text| serde_json::from_str::<HealthState>(&text).ok());
    match parsed {
        Some(state) if state.version == STATE_VERSION => state,
        _ => HealthState {
            version: STATE_VERSION,
            resolved: BTreeMap::new(),
        },
    }
}

/// Persist the rename cache when it changed.
fn write_state(path: &Path, state: &HealthState) -> bool {
    let Ok(text) = serde_json::to_string_pretty(state) else {
        return false;
    };
    write_if_changed(path, &(text + "\n"))
}

/// Write `text` to `path` only when the file's bytes differ; `true` when the
/// file was written. A write failure is a no-op, never an error: the pass is
/// advisory, and the next open retries.
fn write_if_changed(path: &Path, text: &str) -> bool {
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return false;
    }
    if let Some(parent) = path.parent() {
        if std::fs::create_dir_all(parent).is_err() {
            return false;
        }
    }
    std::fs::write(path, text).is_ok()
}


/// Whether a `[[target]]` is a real link shape for the health check: a path
/// (`decision/…`, `src/…`) or a bare knowledge slug (`2026-08-23-…`). TOML
/// array headers (`[[bin]]`, `[[patch.unused]]`) and word mentions
/// (`[[links]]`) are not links — `extract_links` cannot tell them apart, so
/// the check filters here. `extract_links` itself is left alone: its output
/// feeds the row data the wiki-link surface resolves.
fn looks_like_link_target(target: &str) -> bool {
    let target = target.trim();
    target.contains('/') || starts_with_date(target)
}

/// `YYYY-MM-DD-…` — a bare knowledge slug.
fn starts_with_date(target: &str) -> bool {
    let bytes = target.as_bytes();
    bytes.len() >= 11
        && bytes[..4].iter().all(u8::is_ascii_digit)
        && bytes[4] == b'-'
        && bytes[5..7].iter().all(u8::is_ascii_digit)
        && bytes[7] == b'-'
        && bytes[8..10].iter().all(u8::is_ascii_digit)
        && bytes[10] == b'-'
}

/// The names a `[[link]]` may match by name alone: every knowledge file stem
/// and every live record title, lowercased.
fn link_names(records: &[(String, KnowledgeRecord)], rows: &[Memory]) -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    for (_, record) in records {
        names.insert(record.slug.to_lowercase());
        names.insert(normalize_title(&record.title));
    }
    for row in rows {
        if row.superseded_by.is_some() || row.quarantined.is_some() {
            continue;
        }
        let bare = bare_title(&row.title);
        let normalized = normalize_title(&bare);
        if !normalized.is_empty() {
            names.insert(normalized);
        }
    }
    names
}

/// Whether one link points at something that exists.
fn link_resolves(
    root: &Path,
    knowledge_dir: &Path,
    names: &BTreeSet<String>,
    link: &KnowledgeLink,
) -> bool {
    let target = link.target.trim();
    if target.is_empty() {
        return true;
    }
    let named =
        |name: &str| names.contains(&name.to_lowercase()) || names.contains(&normalize_title(name));
    match link.kind {
        KnowledgeLinkKind::Knowledge => {
            knowledge_dir.join(format!("{target}.md")).is_file()
                || target
                    .split_once('/')
                    .is_some_and(|(_, slug)| named(slug))
        }
        KnowledgeLinkKind::Plan => {
            let id = target.strip_prefix("plan/").unwrap_or(target);
            root.join(".coding/plans").join(format!("{id}.md")).is_file() || named(id)
        }
        KnowledgeLinkKind::Review => {
            let stem = target.strip_prefix("review/").unwrap_or(target);
            root.join(".coding/reviews")
                .join(format!("{stem}.md"))
                .is_file()
                || named(stem)
        }
        KnowledgeLinkKind::File => root.join(target).exists() || named(target),
        KnowledgeLinkKind::Other => named(target),
    }
}

/// Live typed semantic records grouped by record type and normalized title.
///
/// Only the authored knowledge classes (SPEC / DECISION / BUG / HOW) are
/// listed: plan and review digests are generated from files nobody can
/// supersede, and on the live store they made 141 of 143 groups — enough to
/// hide the one real collision.
fn duplicate_titles(rows: &[Memory]) -> Vec<DuplicateTitle> {
    let mut groups: BTreeMap<(String, String), Vec<(String, String)>> = BTreeMap::new();
    for row in rows {
        if row.tier != MemoryTier::Semantic
            || !matches!(
                row.record_type,
                MemoryRecordType::Spec
                    | MemoryRecordType::Decision
                    | MemoryRecordType::Bug
                    | MemoryRecordType::How
            )
        {
            continue;
        }
        if row.superseded_by.is_some() || row.quarantined.is_some() {
            continue;
        }
        let bare = bare_title(&row.title);
        let key = normalize_title(&bare);
        if key.is_empty() {
            continue;
        }
        let place = row
            .data
            .get("rel_path")
            .and_then(|value| value.as_str())
            .map(str::to_string)
            .unwrap_or_else(|| format!("id {}", row.id));
        groups
            .entry((row.record_type.as_str().to_string(), key))
            .or_default()
            .push((place, bare));
    }
    let mut out = Vec::new();
    for ((record_type, _), mut members) in groups {
        if members.len() < 2 {
            continue;
        }
        members.sort();
        let Some(record_type) = MemoryRecordType::from_str_opt(&record_type) else {
            continue;
        };
        out.push(DuplicateTitle {
            record_type,
            title: members[0].1.clone(),
            records: members.into_iter().map(|(place, _)| place).collect(),
        });
    }
    out
}

/// The title without its typed prefix (`"BUG: crash"` → `"crash"`).
///
/// `pub(crate)` for the digest sweep in `integrity.rs`, which groups plan and
/// review digests by the same bare title the health report uses.
pub(crate) fn bare_title(title: &str) -> String {
    for prefix in ["SPEC:", "DECISION:", "BUG:", "PLAN:", "HOW:", "REVIEW:"] {
        if let Some(rest) = title.strip_prefix(prefix) {
            return rest.trim().to_string();
        }
    }
    title.trim().to_string()
}

/// Lowercase; every run of non-alphanumeric characters collapses to one space;
/// trimmed. `"BUG:  Same  crash!"` and `"bug: same crash"` normalize alike.
///
/// `pub(crate)` for the digest sweep in `integrity.rs`, so a twin is matched
/// exactly as the health report matches duplicate titles.
pub(crate) fn normalize_title(title: &str) -> String {
    let mut out = String::with_capacity(title.len());
    let mut pending_space = false;
    for ch in title.chars() {
        if ch.is_alphanumeric() {
            if pending_space && !out.is_empty() {
                out.push(' ');
            }
            pending_space = false;
            for lower in ch.to_lowercase() {
                out.push(lower);
            }
        } else {
            pending_space = true;
        }
    }
    out
}

/// `agent.md`'s size, raw and as each workflow scope loads it.
fn measure_constitution(root: &Path) -> ConstitutionSize {
    let Ok(raw_text) = std::fs::read_to_string(root.join("agent.md")) else {
        return ConstitutionSize::default();
    };
    let constitution = Constitution {
        global: String::new(),
        project: raw_text.clone(),
    };
    let scoped = |scope: ConstitutionScope| {
        let text = constitution.scoped(scope).project;
        Size {
            lines: text.lines().count(),
            bytes: text.len(),
        }
    };
    ConstitutionSize {
        present: true,
        raw: Size {
            lines: raw_text.lines().count(),
            bytes: raw_text.len(),
        },
        classic: scoped(ConstitutionScope::Classic),
        team: scoped(ConstitutionScope::Team),
    }
}

/// The report's full text — deterministic: no timestamp, no commit, every list
/// sorted, so unchanged findings produce identical bytes.
fn render_report(
    stale_paths: &[StaleRecord],
    unresolved_links: &[UnresolvedLink],
    duplicate_titles: &[DuplicateTitle],
    constitution: &ConstitutionSize,
) -> String {
    let mut out = String::new();
    out.push_str(REPORT_HEADER);
    out.push_str("\n\n# Memory health\n\n");
    out.push_str(&format!(
        "- {} records cite missing paths\n",
        stale_paths.len()
    ));
    out.push_str(&format!("- {} unresolved links\n", unresolved_links.len()));
    out.push_str(&format!(
        "- {} duplicate titles\n",
        duplicate_titles.len()
    ));
    out.push_str(&render_constitution_counts(constitution));

    out.push_str("\n## Stale paths\n\n");
    if stale_paths.is_empty() {
        out.push_str("none\n");
    }
    for record in stale_paths {
        out.push_str(&format!("- `{}`\n", record.rel_path));
        for moved in &record.moved {
            match &moved.to {
                Some(to) => out.push_str(&format!("  - `{}` -> `{to}`\n", moved.from)),
                None => out.push_str(&format!("  - `{}` gone\n", moved.from)),
            }
        }
    }

    out.push_str("\n## Unresolved links\n\n");
    if unresolved_links.is_empty() {
        out.push_str("none\n");
    }
    for link in unresolved_links {
        out.push_str(&format!(
            "- `{}`: `[[{}]]`\n",
            link.rel_path, link.target
        ));
    }

    out.push_str("\n## Duplicate titles\n\n");
    if duplicate_titles.is_empty() {
        out.push_str("none\n");
    }
    for group in duplicate_titles {
        out.push_str(&format!(
            "- {} \"{}\" — {} live records ({})\n",
            group.record_type.as_str().to_uppercase(),
            group.title,
            group.records.len(),
            group.records.join(", ")
        ));
    }

    out.push_str("\n## agent.md size\n\n");
    if !constitution.present {
        out.push_str("absent\n");
    } else {
        out.push_str(&format!(
            "- raw: {} lines, {} KB\n",
            constitution.raw.lines,
            kb(constitution.raw.bytes)
        ));
        out.push_str(&render_constitution_scope("classic", &constitution.classic));
        out.push_str(&render_constitution_scope("team", &constitution.team));
    }
    out
}

/// The counts line for `agent.md` in the report's summary block.
fn render_constitution_counts(constitution: &ConstitutionSize) -> String {
    if !constitution.present {
        return "- agent.md: absent\n".to_string();
    }
    let over: Vec<&str> = [("classic", constitution.classic), ("team", constitution.team)]
        .iter()
        .filter(|(_, size)| size.over_budget())
        .map(|(name, _)| *name)
        .collect();
    let verdict = if over.is_empty() {
        "within budget".to_string()
    } else {
        format!("over budget: {}", over.join(", "))
    };
    format!(
        "- agent.md: {} lines / {} KB (classic), {} lines / {} KB (team) — {verdict}\n",
        constitution.classic.lines,
        kb(constitution.classic.bytes),
        constitution.team.lines,
        kb(constitution.team.bytes)
    )
}

/// One scoped `agent.md` line in the report's size section.
fn render_constitution_scope(name: &str, size: &Size) -> String {
    let verdict = if size.over_budget() {
        "over budget"
    } else {
        "within budget"
    };
    format!(
        "- {name}: {} lines, {} KB — {verdict} ({} lines / {} KB)\n",
        size.lines,
        kb(size.bytes),
        CONSTITUTION_MAX_LINES,
        kb(CONSTITUTION_MAX_BYTES)
    )
}

/// Bytes as a one-decimal kilobyte figure (`25.0 KB`).
fn kb(bytes: usize) -> String {
    format!("{:.1}", bytes as f64 / 1024.0)
}

/// The `data` JSON with `moved_paths` set to `moved` (removed when empty), or
/// `None` when the stored value already matches — an unchanged row is never
/// rewritten.
fn merge_moved_paths(data: &serde_json::Value, moved: &[MovedPath]) -> Option<serde_json::Value> {
    let mut map = match data {
        serde_json::Value::Object(map) => map.clone(),
        _ => serde_json::Map::new(),
    };
    if moved.is_empty() {
        map.remove(MOVED_PATHS_KEY)?;
        return Some(serde_json::Value::Object(map));
    }
    let value = serde_json::to_value(moved).ok()?;
    if map.get(MOVED_PATHS_KEY) == Some(&value) {
        return None;
    }
    map.insert(MOVED_PATHS_KEY.to_string(), value);
    Some(serde_json::Value::Object(map))
}

/// The indexer's fresh metadata `data` carrying the row's existing
/// `moved_paths` stamp over — the reconcile-safe form of a knowledge row's
/// metadata (plan 373dec00 step 13).
///
/// Both reconcile paths re-assert a knowledge row's `data` from its FILE
/// (a full [`crate::memory::indexer::index_derived`] run when the corpus
/// changed, and the targeted reindex on every knowledge write). That fresh
/// value knows nothing about the stamp this pass writes, so without this
/// carry-over a routine reconcile — which happens on any open whose corpus
/// moved — would silently erase it. Only [`MOVED_PATHS_KEY`] is inherited:
/// `links`, `rel_path` and the rest always come from the file, which is their
/// truth. The pass itself ([`merge_moved_paths`]) stays the one writer that
/// sets or removes the stamp.
pub(crate) fn keep_moved_paths(
    fresh: &serde_json::Value,
    existing: &serde_json::Value,
) -> serde_json::Value {
    let Some(stamped) = existing.get(MOVED_PATHS_KEY) else {
        return fresh.clone();
    };
    match fresh {
        serde_json::Value::Object(map) => {
            let mut merged = map.clone();
            merged.insert(MOVED_PATHS_KEY.to_string(), stamped.clone());
            serde_json::Value::Object(merged)
        }
        // A non-object fresh value cannot carry the key; the fresh value
        // stands (the next pass re-stamps it if the record still earns it).
        other => other.clone(),
    }
}

