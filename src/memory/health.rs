//! The memory check pass — the deterministic, model-free sweep that flags
//! knowledge records the repo has moved past (plan 373dec00 step 5).
//!
//! Four checks, all read against the record files plus git history:
//!
//! - **stale paths**: a record body citing a repo path that no longer exists
//!   (the citation rule is [`CITATION_PATTERN`]). A path git can follow through
//!   a rename is reported with its new home (`a -> b`); one that was simply
//!   deleted is reported `gone`.
//! - **unresolved links**: `[[wiki-links]]` whose target matches no knowledge
//!   file stem, no record title, and no file on disk.
//! - **duplicate titles**: live typed semantic records sharing a record type
//!   *and* a normalized title — the corpus' one real duplication risk, because
//!   a slug carries its date and the same title on two dates yields two files.
//! - **constitution size**: `agent.md` measured the way a session loads it —
//!   through [`Constitution::scoped`] per workflow — against the 200-line /
//!   25 KB guidance.
//!
//! Results go to `.coding/knowledge/HEALTH.md` (generated and gitignored;
//! rewritten only when its bytes change) and, for stale paths, into each
//! affected record's derived row as `data.moved_paths`, which `memory_search`
//! renders as `[cites moved paths: a -> b; c gone]`. Authored record bodies are
//! never edited: the file is the truth, and its author supersedes it.
//!
//! The pass is cheap on a warm cache. Existence checks are `stat` calls; the
//! only git spawns are rename lookups for paths the cache has never resolved.
//! `.coding/knowledge/.health-state.json` remembers each resolution
//! (`{"version":1,"resolved":{"<from>":"<to>"|null}}`) — git history only
//! grows, so a resolution stays valid until its `to` vanishes from disk.

